import io
p=r'platform-docs\19-多场景平台总体设计基线.md'
s=io.open(p,encoding='utf-8').read()
s=s.replace('> 状态：设计基线 v1.0  ','> 状态：设计基线 v1.1  ')
start=s.index('## 1. 目标与原则')
end=s.index('## 2. 总体架构')
new='''## 1. 目标、约束与设计原则

### 1.1 总目标

建设一个支持多场景、多租户、统一权限、统一审批、统一设备能力的空间资产运营平台。

目标不是“把页面做出来”，而是：

```text
业务能闭环
数据能可信
权限能控制
系统能扩展
运营能持续
```

### 1.2 八项核心目标

```text
1. 多场景可扩展
2. 业务闭环
3. 操作简单好用
4. 显示全面可读
5. 安全合规可审计
6. 数据准确一致
7. 稳定高效可运维
8. 可持续交付与演进
```

目标说明：

| 目标 | 含义 | 不是 |
|---|---|---|
| 多场景可扩展 | 新增场景复用平台能力，不复制核心代码 | 不是每个场景各做一套 |
| 业务闭环 | 每个业务对象有状态、动作、结果和日志 | 不是只有列表和新增 |
| 操作简单好用 | 选择、填写、提交、处理都顺畅 | 不是控件越少越好 |
| 显示全面可读 | 关键字段、状态、关联信息完整 | 不是字段堆得越多越好 |
| 安全合规可审计 | 授权、脱敏、审计、留痕 | 不是只做登录 |
| 数据准确一致 | 同一对象一个事实来源，同一指标一个口径 | 不是每个页面各算一套 |
| 稳定高效可运维 | 高峰可用、任务可恢复、问题可定位 | 不是只追求页面打开 |
| 可持续交付与演进 | 组件复用、接口契约、版本可回滚 | 不是一次性交付 |

### 1.3 技术约束

```text
保持新前端
统一组件和页面模板
不把新前端本身当作业务目标
新前端服务于“可持续交付与演进”
```

### 1.4 支撑目标

```text
业务可运营
配置可治理
接口可开放
成本可控制
```

这些目标不单独扩大核心目标数量，但必须体现在设计中。

### 1.5 设计原则

```text
平台能力下沉，场景能力上浮
共享对象统一，场景字段隔离
流程可配置，但不牺牲资金安全
权限后端强制，不依赖前端隐藏
编码展示友好，不显示裸 ID
业务对象有状态、有动作、有日志
页面可复用，不为单页重复造轮子
数据有来源，指标有口径
关键动作可审计，异常可定位
```

### 1.6 目标—设计—验收映射

| 核心目标 | 对应设计 | 验收证据 |
|---|---|---|
| 多场景可扩展 | 第 2、3、5 章：平台层/场景层、共享对象、场景扩展点 | 新场景不复制平台核心；共享能力复用 |
| 业务闭环 | 第 3、6、10、11 章：状态机、审批、详情页、标准页面 | 每个对象有详情、状态和下一步动作 |
| 操作简单好用 | 第 10 章：页面模板、选择器、草稿、批量 | 选择可搜索、可层级、可恢复、可批量 |
| 显示全面可读 | 第 10 章：列表/详情/字段/编码展示 | 无裸 ID、无英文枚举、关键字段完整 |
| 安全合规可审计 | 第 4、12 章：租户、数据范围、字段权限、审计 | 越权被拒绝、导出受控、关键操作有日志 |
| 数据准确一致 | 第 3、5、7 章：主数据、编码、财务口径 | 账单收款对账一致、指标口径统一 |
| 稳定高效可运维 | 第 12 章：异步、监控、备份、恢复 | 批量可重试、问题可定位、备份可恢复 |
| 可持续交付与演进 | 第 10、12、13 章：设计系统、组件、测试、版本 | 新页面复用模板；发布可回滚；契约稳定 |

### 1.7 目标优先级

发生冲突时按以下顺序决策：

```text
1. 安全合规
2. 数据准确
3. 业务闭环
4. 稳定可用
5. 操作体验
6. 扩展效率
```

原则：

```text
不能为了页面好看牺牲权限
不能为了上线速度牺牲资金口径
不能为了单场景需求破坏平台边界
```

---

'''
s=s[:start]+new+s[end:]
io.open(p,'w',encoding='utf-8',newline='').write(s)
